"""Detection signals for Provenance Guard.

Every signal returns {"score": float | None, "details": dict}
where score 0.0 = reads human-written, 1.0 = reads AI-generated (see planning.md §1).
"""

from __future__ import annotations

import json
import math
import os
import re
import statistics

from dotenv import load_dotenv

load_dotenv()

# The model named in the assignment (meta-llama/llama-4-scout-17b-16e-instruct) is no longer
# served on Groq, so the default is a currently available model. Override with GROQ_MODEL in .env.
GROQ_MODEL = os.getenv("GROQ_MODEL", "qwen/qwen3.8-27b")

WORD_RE = re.compile(r"[A-Za-z']+")
# Sentence boundaries: ., !, ? (possibly repeated) or a line break (poems / casual posts).
SENTENCE_SPLIT_RE = re.compile(r"(?<=[.!?])\s+|\n+")


def _clamp(x: float, lo: float = 0.0, hi: float = 1.0) -> float:
    return max(lo, min(hi, x))


def _linear(x: float, at_zero: float, at_one: float) -> float:
    """Map x linearly so x == at_zero -> 0 and x == at_one -> 1, clamped to [0, 1]."""
    return _clamp((x - at_zero) / (at_one - at_zero))


def words(text: str) -> list[str]:
    return WORD_RE.findall(text)


def sentences(text: str) -> list[str]:
    return [s.strip() for s in SENTENCE_SPLIT_RE.split(text.strip()) if s and words(s)]


# --------------------------------------------------------------------------------------------
# Signal 1 — LLM judge (Groq)
# --------------------------------------------------------------------------------------------

LLM_SYSTEM_PROMPT = """You are an attribution analyst for a creative-writing platform.
Estimate how likely it is that the text was generated by an AI language model rather than
written by a person. Consider: generic or hedged framing, evenly balanced structure, stock
transitions, absence of concrete personal detail, and overly polished uniform prose (AI-like)
versus idiosyncratic voice, specific lived detail, irregular rhythm, typos and slang (human-like).
Formal or non-native-sounding writing is NOT by itself evidence of AI.
Respond with JSON only: {"ai_probability": <number 0 to 1>, "reasoning": "<one sentence>"}"""

_groq_client = None


def _client():
    global _groq_client
    if _groq_client is None:
        from groq import Groq

        _groq_client = Groq(api_key=os.environ["GROQ_API_KEY"], timeout=20.0, max_retries=1)
    return _groq_client


def llm_signal(text: str) -> dict:
    """Ask the Groq-hosted LLM for an AI probability. Returns score None if the call fails."""
    try:
        resp = _client().chat.completions.create(
            model=GROQ_MODEL,
            messages=[
                {"role": "system", "content": LLM_SYSTEM_PROMPT},
                {"role": "user", "content": f"Text to assess:\n\"\"\"\n{text}\n\"\"\""},
            ],
            response_format={"type": "json_object"},
            temperature=0,
            max_tokens=300,
        )
        data = json.loads(resp.choices[0].message.content)
        score = _clamp(float(data["ai_probability"]))
        return {
            "score": round(score, 3),
            "details": {"model": GROQ_MODEL, "reasoning": str(data.get("reasoning", ""))[:400]},
        }
    except Exception as exc:  # network error, rate limit, bad JSON, missing key...
        return {
            "score": None,
            "details": {"model": GROQ_MODEL, "error": f"{type(exc).__name__}: {exc}"[:300]},
        }


# --------------------------------------------------------------------------------------------
# Signal 2 — Stylometric uniformity
# --------------------------------------------------------------------------------------------

SLANG = {
    "lol", "lmao", "omg", "gonna", "wanna", "gotta", "kinda", "sorta", "honestly", "ok", "okay",
    "yeah", "yep", "nope", "like", "literally", "tbh", "idk", "btw", "ugh", "haha", "dude", "cuz",
    "y'all", "ain't", "gotcha", "nah", "super", "pretty", "stuff",
}


def stylometric_signal(text: str) -> dict:
    ws = words(text)
    sents = sentences(text)
    n_words = len(ws)
    if n_words == 0:
        return {"score": None, "details": {"error": "no words"}}

    # Burstiness: coefficient of variation of sentence length.
    lengths = [len(words(s)) for s in sents] or [n_words]
    mean_len = statistics.fmean(lengths)
    cv = statistics.pstdev(lengths) / mean_len if len(lengths) > 1 and mean_len else 0.0
    uniformity = 1.0 - _linear(cv, 0.20, 0.65)  # CV <= 0.20 -> 1.0 (AI-like), >= 0.65 -> 0.0

    # Word length.
    avg_word_len = statistics.fmean(len(w.strip("'")) for w in ws)
    word_len_score = _linear(avg_word_len, 4.2, 5.4)

    # Informality markers (human-like).
    lower_starts = sum(1 for s in sents if s[0].islower())
    lone_i = sum(1 for w in ws if w == "i")
    bangs_q = text.count("!") + text.count("?")
    ellipses = text.count("...") + text.count("…")
    all_caps = sum(1 for w in ws if len(w) >= 2 and w.isupper() and w not in {"AI", "US", "UK", "TV"})
    slang = sum(1 for w in ws if w.lower() in SLANG)
    informal_hits = lower_starts + lone_i + bangs_q + ellipses + all_caps + slang
    informal_rate = informal_hits / n_words
    formality = 1.0 - _clamp(informal_rate * 12)

    score = 0.40 * uniformity + 0.30 * word_len_score + 0.30 * formality
    return {
        "score": round(score, 3),
        "details": {
            "sentence_count": len(lengths),
            "sentence_length_cv": round(cv, 3),
            "avg_word_length": round(avg_word_len, 2),
            "informal_markers": informal_hits,
            "subscores": {
                "uniformity": round(uniformity, 3),
                "word_length": round(word_len_score, 3),
                "formality": round(formality, 3),
            },
        },
    }


# --------------------------------------------------------------------------------------------
# Signal 3 — AI-phrase markers (stretch: ensemble)
# --------------------------------------------------------------------------------------------

AI_MARKERS = [
    "it is important to note", "it's important to note", "it is worth noting", "it's worth noting",
    "it is essential to", "it is equally essential", "it is crucial to", "furthermore", "moreover",
    "additionally", "in conclusion", "in summary", "overall,", "delve", "delves", "tapestry",
    "testament to", "paradigm shift", "transformative", "stakeholders", "landscape of",
    "in today's fast-paced", "in today's digital", "ever-evolving", "ever-changing",
    "plays a crucial role", "plays a vital role", "plays a pivotal role", "a myriad of",
    "navigate the complexities", "navigating the", "foster", "fostering", "leverage",
    "leveraging", "robust", "seamless", "holistic", "multifaceted", "nuanced", "underscores",
    "embark on", "realm of", "unlock the", "harness the", "ensure responsible",
    "various sectors", "numerous benefits", "on the other hand", "a rich tapestry",
]


def marker_signal(text: str) -> dict:
    lowered = text.lower()
    n_words = len(words(text))
    if n_words == 0:
        return {"score": None, "details": {"error": "no words"}}
    found = [m for m in AI_MARKERS if m in lowered]
    hits = sum(lowered.count(m) for m in found)
    per_100 = hits / n_words * 100
    score = 1.0 - math.exp(-0.35 * per_100)
    return {
        "score": round(score, 3),
        "details": {"hits": hits, "hits_per_100_words": round(per_100, 2), "phrases": found[:10]},
    }


def run_all(text: str) -> dict:
    return {
        "llm": llm_signal(text),
        "stylometric": stylometric_signal(text),
        "markers": marker_signal(text),
    }
